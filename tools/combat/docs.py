"""Generated reference pages for docs/COMBAT.md: written from the same data as data/combat/, so they never
drift. build.py calls write_all()."""

import os

import animations
import clans
import enemies
import squad
import taijutsu
import techniques
import weapons
from common import ROOT

DOCS = os.path.join(ROOT, "docs", "combat")
HEADER = "<!-- Generated by tools/combat/build.py from tools/combat/*.py: edit the sources, not this file. -->\n\n"


def esc(x):
    return str(x).replace("|", "/").replace("\n", " ")


def signs(t):
    return " ".join(s.capitalize() for s in t["signs"]) if t["signs"] else "none"


def teach(t):
    return ", ".join(x.replace("mentor:", "").replace("role:", "") for x in t["teach"])


def counters(t):
    return esc(t["counters"]) if isinstance(t["counters"], str) else esc("; ".join(t["counters"]))


def tech_rows(lst):
    out = ["| Id | Name | Nature | Rank | Level | Signs | Chakra | Cast | Cooldown | Power | Mechanic | Counters | Taught by | Slice |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for t in lst:
        out.append("| `%s` | %s | %s | %s | %d | %s | %d | %d | %d | %s | %s | %s | %s | %s%s |" % (
            t["id"], esc(t["name"]), t["nature"], t["rank"].upper(), t["level"], signs(t), t["chakra"], t["cast_ticks"],
            t["cooldown_ticks"], t["power"], esc(t["mechanic"]), counters(t), esc(teach(t)), t["slice"], " (beta)" if t.get("beta") else ""))
    return "\n".join(out)


def techniques_page():
    fams = [("Neutral ninjutsu", techniques.NEUTRAL), ("Fire", techniques.FIRE), ("Wind", techniques.WIND), ("Lightning", techniques.LIGHTNING),
            ("Earth", techniques.EARTH), ("Water", techniques.WATER), ("Genjutsu", techniques.GENJUTSU), ("Medical ninjutsu", techniques.MEDICAL),
            ("Sensing", techniques.SENSING), ("Fuinjutsu", techniques.FUINJUTSU), ("Weapon techniques", techniques.WEAPON_JUTSU)]
    body = [HEADER + "# Technique catalogue\n",
            "Every technique outside the clans (those are in [clans.md](clans.md)), E to S. Cast, cooldown are ticks (20 a second); "
            "chakra is the base cost before control, your own nature (x0.75) and mastery; power is base damage before level, pillar and nature "
            "scaling (0 for techniques that control, move or protect). The rules for each family are in [../COMBAT.md](../COMBAT.md).\n"]
    for name, lst in fams:
        body.append("## %s (%d)\n\n%s\n" % (name, len(lst), tech_rows(lst)))
    body.append("## Chakra movement\n\n| Id | Name | Slice | Cost | Effect | Taught by |\n|---|---|---|---|---|---|")
    for m in techniques.MOVEMENT:
        cost = m.get("chakra", m.get("chakra_per_second", 0))
        body.append("| `%s` | %s | %s | %s%s | %s | %s |" % (m["id"], m["name"], m["slice"], cost, "/s" if "chakra_per_second" in m else "",
                                                      esc(m["effect"]), ", ".join(x.replace("mentor:role:", "") for x in m["teach"])))
    return "\n".join(body) + "\n"


def clans_page():
    body = [HEADER + "# Clan techniques and kekkei genkai\n",
            "All 25 clans in four tiers: tier 1 at Genin (level 10), tier 2 at Chunin (20), tier 3 at Jonin (32), tier 4 on the road to Hokage (44). "
            "The player is clanless (the owner's decision), so these are the kits of clan residents, teammates, rivals and enemies; the player's "
            "clan route is each clan's lesser technique, learned at clan friendship 7. Kekkei genkai come only through clan blood.\n"]
    for c in clans.CLANS:
        body.append("## %s (%s)\n" % (c["name"], c["standing"]))
        p = ", ".join("%s %s" % (k, v) for k, v in c["passives"].items())
        body.append("Passives: %s. Suggested nature: %s.%s\n" % (p or "none", ", ".join(c["suggested_nature"]) or "none",
                                                               " Style: `%s`." % c["style"] if c.get("style") else ""))
        if c.get("kekkei_genkai"):
            k = c["kekkei_genkai"]
            body.append("Kekkei genkai, **%s**: %s\n" % (k["name"], "; ".join("stage %d (%s): %s" % (s["stage"], s["slice"], esc(s.get("gives", s.get("note", ""))))
                                                                         for s in k["stages"])))
        body.append(tech_rows(c["techniques"] + ([c["lesser"]] if c.get("lesser") else [])) + "\n")
    return "\n".join(body) + "\n"


def move_rows(moves):
    out = ["| Move | Input | Tier | Damage | Poise | Frames | Window | Stamina | Effects | Slice |", "|---|---|---|---|---|---|---|---|---|---|"]
    for m in moves:
        fx = ", ".join("%s %s" % (k, v) if v is not True else k for k, v in m.get("effects", {}).items())
        if m.get("momentum_cost"):
            fx = ("momentum %d, " % m["momentum_cost"]) + fx
        out.append("| %s | %s | %d | %s | %s | %s | %s | %s | %s | %s |" % (m["id"], " ".join(m["input"]), m["tier"], m["damage"], m["poise"],
                                                                        "/".join(map(str, m["frames"])), "-".join(map(str, m["window"])),
                                                                        m["stamina"], esc(fx), m.get("slice", "")))
    return "\n".join(out)


def styles_page():
    body = [HEADER + "# Styles and combo trees\n",
            "Inputs: L light, H heavy (hold 8 ticks), D after a dodge, P after a parry, J in the air, X a dash, G while guarding, T a throw. Frames are "
            "startup/active/recovery in ticks; the window is when the next input is taken after the active frames (0-0 ends the string). Every style "
            "builds on Academy taijutsu: paths a style leaves out keep the Academy move. Moves marked weapon_mult multiply the held weapon's damage.\n"]
    for s in taijutsu.STYLES + weapons.WEAPON_STYLES:
        body.append("## %s (`%s`, %s)\n\n%s Who: %s. Mentor: %s. From %s.\n\n%s\n" % (s["name"], s["id"], s["pillar"], s["feel"], s["who"],
                                                                                   s["mentor"].replace("role:", ""), s["slice"], move_rows(s["moves"])))
    body.append("## Inner gates\n\n%s.\n\n| Gate | Name | Slice | Damage | Speed | Health drain a second (HP per 20 max HP) | Lasts | Strain |\n|---|---|---|---|---|---|---|---|" % taijutsu.GATES["who"])
    for g in taijutsu.GATES["gates"]:
        body.append("| %d | %s | %s | %s | %s | %s | %s | %s |" % (g["n"], g["name"], g["slice"], g.get("damage", ""), g.get("speed", ""),
                                                                g.get("hp_drain_per_second", ""), g.get("max_ticks", ""), g.get("strain_ticks", g.get("note", ""))))
    return "\n".join(body) + "\n"


def bestiary_page():
    body = [HEADER + "# Bestiary, groups and bosses\n",
            "Every enemy the story uses, by loadout file (data/combat/enemies/<id>.json). Story enemies are written by role and neutral ids; what a story "
            "boss is lives only in the story bible, keyed by its id.\n",
            "| Id | Name | Kind | Tier | Rank | Levels | Band | Weapons | Techniques | Traits | Slice |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for e in enemies.HUMANS + enemies.ANIMALS:
        body.append("| `%s` | %s | %s | %s | %s | %d-%d | %s | %s | %s | %s | %s |" % (
            e["id"], e["name"], e["kind"], e["tier"], e["rank"], e["levels"][0], e["levels"][1], e["band"],
            ", ".join(w.replace("item:", "") for w in e["weapons"]) or "-", ", ".join(t.replace("combat:", "") for t in e["techniques"]) or "-",
            esc(", ".join(e["traits"]) + ("; " + e["note"] if e.get("note") else "")) or "-", e["slice"]))
    body.append("\n## Groups\n\n| Id | Members | Slice |\n|---|---|---|")
    for g in enemies.GROUPS:
        mem = []
        for m in g["members"]:
            who = m.get("enemy", m.get("entity")) or " or ".join(x.replace("combat:enemy.", "") for x in m["pick"])
            mem.append("%d x %s" % (m.get("count", 1), who.replace("combat:enemy.", "")))
        body.append("| `%s` | %s | %s |" % (g["id"], ", ".join(mem), g["slice"]))
    body.append("\n## Bosses\n")
    for b in enemies.BOSSES:
        body.append("### `%s`: %s (chapter %s, level %d, %s)\n" % (b["id"], b["name"], b["chapter"], b["level"], b["slice"]))
        body.append("Base `%s`, health x%s, poise %d, damage x%s%s. Win: %s. Lose: %s.%s\n" % (
            b["base"], b["hp_mult"], b["poise"], b["damage_mult"], ", non-lethal" if b["nonlethal"] else "", esc(b["win"]), esc(b["lose"]),
            " Story beats: in the story bible under this id." if b.get("story") else ""))
        if b["phases"]:
            body.append("| From health | Phase | Behaviour | Adds | Openings | Signature tell |\n|---|---|---|---|---|---|")
            for p in b["phases"]:
                body.append("| %d%% | %s | %s | %s | %s | %s |" % (round(p["at_hp"] * 100), p["name"], esc(p["behaviour"]),
                                                              ", ".join(x.replace("combat:", "") for x in p.get("adds", [])) or "-",
                                                              esc(p.get("openings", "-")), esc(p.get("signature_tell", "-"))))
        if b.get("notes"):
            body.append("\n%s" % esc(b["notes"]))
        body.append("")
    return "\n".join(body) + "\n"


def animations_page():
    body = [HEADER + "# Animation clips\n",
            "Every pose and clip the player and residents need for combat, keyed the way VF keys its clips (tools/combat/animations.py; keyframes are "
            "authored later into the same table). P0: the Phase 0 spike and Beta 1; P1: Beta 2; P2: Beta 3; P3: later. fp: needs the first-person arm path.\n"]
    counts = animations.summary()
    body.append("Counts: " + ", ".join("%s %d" % (k, counts[k]) for k in sorted(counts)) + ", total %d.\n" % len(animations.CLIPS))
    for pr in ("P0", "P1", "P2", "P3"):
        body.append("## %s\n\n| Clip | Ticks | Loop | Who | First person | Note |\n|---|---|---|---|---|---|" % pr)
        for cid, c in animations.CLIPS.items():
            if c["priority"] == pr:
                body.append("| `%s` | %d | %s | %s | %s | %s |" % (cid, c["ticks"], "yes" if c["loop"] else "", c["who"], "yes" if c["fp"] else "",
                                                             esc(c.get("note", ""))))
        body.append("")
    return "\n".join(body) + "\n"


def write_all():
    os.makedirs(DOCS, exist_ok=True)
    pages = {"techniques.md": techniques_page(), "clans.md": clans_page(), "styles.md": styles_page(), "bestiary.md": bestiary_page(),
             "animations.md": animations_page()}
    for name, text in pages.items():
        with open(os.path.join(DOCS, name), "w", encoding="utf-8") as f:
            f.write(text)
    return list(pages)
