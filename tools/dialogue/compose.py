"""Composes systematic pools from seeds: tools/dialogue/seeds/*.txt -> tools/dialogue/generated/*.txt (DIALOGUE.md, "Mass production").

Two shapes, both deterministic (the same seeds always write the same files):

Voice kernels: one piece of content said in each personality register. Every variant shares the kernel's group, so
once a player hears it from anyone, the other voices of it are spent too: composition widens who can say a thing,
never how many things there are to hear.

    ## chat.weather  weather=rain  fn=react
    * gutters
    warm:   The gutters are singing again. I put a pot out for the geraniums.
    bold:   Listen to those gutters! Perfect weather for training in the mud.
    proud:  The gutters overflow every time. Someone ought to see to them.
    any:    Hear the gutters? This rain isn't stopping before supper.

  Registers: warm (warmhearted, gentle), bright (playful, curious), bold (adventurous, fiery), calm (thoughtful,
  steadfast), precise (meticulous, pragmatic), quiet (reserved, shy), proud (proud, stern), dreamy (imaginative),
  guard (protective). "any:" is said by every personality the kernel gives no voice of its own.
  A kernel line may also name a clan voice instead (nara: ..., akimichi: ...), or a single personality (fiery: ...).

Slot templates: a frame filled from lists. The last slot's fills are used once each; the others cycle. Use them for
lines whose variety is in the content of the last slot (a shop's wares, an observation), not for padding.

    ## shop.grocer.browse  shop=grocer  fn=commerce  kind=cycle
    = open: Take your time. | Have a look around. | No rush, {player}.
    = what: The radishes came in this morning. | The pickled plums are from my aunt's tree. | ...
    > {=open} {=what}

    python tools/dialogue/compose.py           # write tools/dialogue/generated/*.txt
    python tools/dialogue/compose.py --check   # confirm the generated files are current
"""
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SEEDS, OUT = ROOT / 'seeds', ROOT / 'generated'
REGISTERS = {
    'warm': ['warmhearted', 'gentle'], 'bright': ['playful', 'curious'], 'bold': ['adventurous', 'fiery'],
    'calm': ['thoughtful', 'steadfast'], 'precise': ['meticulous', 'pragmatic'], 'quiet': ['reserved', 'shy'],
    'proud': ['proud', 'stern'], 'dreamy': ['imaginative'], 'guard': ['protective'],
}
ARCHETYPES = [a for v in REGISTERS.values() for a in v]
CLANS = ['senju', 'uzumaki', 'uchiha', 'hyuga', 'nara', 'akimichi', 'yamanaka', 'inuzuka', 'sarutobi', 'aburame', 'hatake',
         'kurama', 'shimura', 'yuhi', 'gekko', 'shiranui', 'morino', 'umino', 'haruno', 'namiashi', 'hagane', 'kinoshita',
         'tsuchigumo', 'suzuran', 'tobari']
GROUPS = ['civilian', 'clanless']


def fail(where, message):
    raise SystemExit(f'{where}: {message}')


def compose(path):
    out, heading, kernel, template = [f'# Generated by compose.py from seeds/{path.name}: edit the seed, not this file.'], None, None, None
    seed = random.Random(path.name)

    def flush_kernel():
        if not kernel:
            return
        covered = set()
        for voice, _ in kernel['lines']:
            covered |= set(REGISTERS.get(voice, [voice] if voice in ARCHETYPES else []))
        for voice, text in kernel['lines']:
            if voice == 'any':
                rest = [a for a in ARCHETYPES if a not in covered]
                tag = f'personality={"|".join(rest)}' if covered else ''
            elif voice in REGISTERS:
                tag = 'personality=' + '|'.join(REGISTERS[voice])
            elif voice in ARCHETYPES:
                tag = f'personality={voice}'
            elif voice in CLANS:
                tag = f'clan={voice}'
            elif voice in GROUPS:
                tag = f'group={voice}'
            else:
                fail(kernel['where'], f'unknown voice {voice!r}')
            out.append(f'## {heading} {tag}'.rstrip())
            out.append(f'{text} ~{kernel["id"]}')

    def flush_template():
        if not template:
            return
        if not template['frames'] or not template['slots']:
            fail(template['where'], 'a template needs "= slot: a | b" lines and a "> frame" line')
        names = list(template['slots'])
        last = names[-1]
        fills = {n: template['slots'][n][:] for n in names}
        for n in names:
            seed.shuffle(fills[n])
        out.append(f'## {heading}')
        for i, unique in enumerate(fills[last]):
            frame = template['frames'][i % len(template['frames'])]
            text = frame
            for n in names:
                value = unique if n == last else fills[n][i % len(fills[n])]
                text = text.replace('{=' + n + '}', value)
            if '{=' in text:
                fail(template['where'], f'unfilled slot in {frame!r}')
            out.append(re.sub(r'\s+', ' ', text).strip())

    for n, raw in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
        line = raw.strip()
        where = f'seeds/{path.name}:{n}'
        if not line or line.startswith('# ') or line == '#':
            continue
        if line.startswith('#!'):
            out.append(line)
        elif line.startswith('## '):
            flush_kernel(); flush_template(); kernel = template = None
            heading = line[3:].strip()
        elif line.startswith('* '):
            flush_kernel()
            if heading is None:
                fail(where, 'a kernel before any heading')
            kid = line[2:].strip()
            if not re.fullmatch(r'[a-z0-9_]+', kid):
                fail(where, f'bad kernel id {kid!r}')
            kernel = {'id': kid, 'lines': [], 'where': where}
        elif line.startswith('= '):
            if template is None:
                template = {'slots': {}, 'frames': [], 'where': where}
            name, _, values = line[2:].partition(':')
            template['slots'][name.strip()] = [v.strip() for v in values.split(' | ') if v.strip()]
        elif line.startswith('> '):
            if template is None:
                fail(where, 'a frame before its slots')
            template['frames'].append(line[2:].strip())
        elif kernel is not None and re.match(r'^[a-z_]+:\s', line):
            voice, _, text = line.partition(':')
            kernel['lines'].append((voice.strip(), text.strip()))
        else:
            fail(where, f'expected a heading, "* kernel", "voice: text", "= slot:" or "> frame": {line[:40]}')
    flush_kernel(); flush_template()
    return '\n'.join(out) + '\n'


def main():
    OUT.mkdir(exist_ok=True)
    stale, written = [], 0
    expected = {}
    for path in sorted(SEEDS.glob('*.txt')):
        expected['gen-' + path.name] = compose(path)
    for name, text in expected.items():
        target = OUT / name
        if '--check' in sys.argv:
            if not target.exists() or target.read_text(encoding='utf-8') != text:
                stale.append(name)
        else:
            target.write_text(text, encoding='utf-8')
            written += text.count('\n## ')
    for old in OUT.glob('gen-*.txt'):
        if old.name not in expected:
            stale.append(old.name) if '--check' in sys.argv else old.unlink()
    if '--check' in sys.argv:
        if stale:
            raise SystemExit(f'generated dialogue is out of date ({", ".join(stale)}): run python tools/dialogue/compose.py')
        print(f'Generated dialogue is up to date: {len(expected)} seed files.')
    else:
        print(f'Composed {len(expected)} seed files into tools/dialogue/generated/.')


if __name__ == '__main__':
    main()
